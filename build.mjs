#!/usr/bin/env node
/**
 * web/build.js — assembles web/index.html and stamps a hash-based Content-Security-Policy.
 *
 *   node web/build.mjs                  # recompute the CSP for the current index.html
 *   node web/build.mjs path/to/page.html # replace the page body with a new artifact export, then stamp
 *
 * Every inline <script> gets a sha256 source in script-src, so an injected inline script cannot run even if
 * some template ever let markup through. The same policy is written to web/_headers (Netlify / Cloudflare
 * Pages) and infra/nginx-headers.conf with the directives a <meta> tag cannot carry (frame-ancestors, HSTS).
 * Keep CONNECT in sync with config.js: the API host the site may talk to.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const INDEX = join(here, "index.html");
const EXTRA = (process.env.API_ORIGIN || "").split(",").map((x) => x.trim()).filter(Boolean);
for (const o of EXTRA) if (!/^https:\/\/[a-z0-9.-]+(:\d+)?$/i.test(o)) throw new Error("API_ORIGIN must be exact https origins, comma-separated: " + o);
const CONNECT = [...EXTRA, "https://api.cadre-us.org", "https://api.coingecko.com", "http://localhost:8080", "http://127.0.0.1:8080"]; // live feeds, the discreet SOL price, and `npm run demo` on this machine
const FONTS_CSS = "https://fonts.googleapis.com", FONTS = "https://fonts.gstatic.com";

let html = readFileSync(INDEX, "utf8");
const page = process.argv[2];
if (page) {
  const src = readFileSync(resolve(page), "utf8");
  const head = html.slice(0, html.indexOf("<body>\n") + 7);
  const tail = html.slice(html.indexOf("\n<script src=\"live.js\"></script>"));
  html = head + src.trim() + "\n" + tail;
  console.log(`body replaced from ${page} (${(src.length / 1024).toFixed(0)} KiB)`);
}

const hashes = [...html.matchAll(/<script(?![^>]*\ssrc=)[^>]*>([\s\S]*?)<\/script>/g)].map((m) => "'sha256-" + createHash("sha256").update(m[1]).digest("base64") + "'");
const csp = [
  "default-src 'self'",
  `script-src 'self' ${[...new Set(hashes)].join(" ")}`,
  `style-src 'self' 'unsafe-inline' ${FONTS_CSS}`,           // the page styles components with inline style attributes; scripts are what matters
  `font-src 'self' ${FONTS} data:`,
  "img-src 'self' data: blob:",
  `connect-src 'self' ${CONNECT.join(" ")}`,
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "manifest-src 'self'",
  "worker-src 'self'",                                      // the push service worker (web/sw.js)
].join("; ");

const meta = `<meta http-equiv="Content-Security-Policy" content="${csp}">\n<meta name="referrer" content="strict-origin-when-cross-origin">`;
html = html.replace(/<meta http-equiv="Content-Security-Policy"[^>]*>\n(<meta name="referrer"[^>]*>\n)?/g, "");
html = html.replace("<meta charset=\"utf-8\">\n", `<meta charset="utf-8">\n${meta}\n`);
writeFileSync(INDEX, html);
console.log(`index.html: ${hashes.length} inline script(s) hashed, CSP stamped`);

/* the same policy as real response headers, plus what a <meta> tag cannot express */
const headerCsp = csp + "; frame-ancestors 'none'; upgrade-insecure-requests"; // nginx: the full policy as a header
// Cloudflare Pages/Workers reject a _headers line over 2000 characters, and the script hashes alone are longer. The page's <meta> policy
// (hashes, connect-src, …) is enforced by the browser anyway; the header adds what a <meta> tag cannot carry.
const shortCsp = "object-src 'none'; base-uri 'self'; form-action 'self'; frame-ancestors 'none'; upgrade-insecure-requests";
const mk = (cspValue) => [
  `Content-Security-Policy: ${cspValue}`,
  "Strict-Transport-Security: max-age=31536000; includeSubDomains; preload",
  "X-Content-Type-Options: nosniff",
  "X-Frame-Options: DENY",
  "Referrer-Policy: strict-origin-when-cross-origin",
  "Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()",
  "Cross-Origin-Opener-Policy: same-origin",
];
const common = mk(shortCsp), commonNginx = mk(headerCsp);
writeFileSync(join(here, "_headers"), `/*\n${common.map((h) => "  " + h).join("\n")}\n\n/sw.js\n  Cache-Control: no-cache\n  Service-Worker-Allowed: /\n\n/*.png\n  Cache-Control: public, max-age=604800\n\n/brand/*\n  Cache-Control: public, max-age=604800\n`);
const infra = join(here, "..", "infra", "nginx-headers.conf");
if (existsSync(dirname(infra))) writeFileSync(infra, `# included from the server block that serves web/ — generated by web/build.js\n${commonNginx.map((h) => { const i = h.indexOf(":"); return `add_header ${h.slice(0, i)} "${h.slice(i + 2)}" always;`; }).join("\n")}\n`);
console.log("_headers and infra/nginx-headers.conf written");
